//comparision operator will return boolean true or false
//>,<,>=,<=,==,!=,===,!==
// = -> assignment operator
// == -> value checking operator(losse comparision)
// === -> value and type checking operator(stric comparision)

let a = 10;
let b = 20;
console.log(a > b);
console.log(a < b);
console.log(a >= b);
console.log(a <= b);
console.log(a == b);
console.log(a != b);
console.log(a === b);
console.log(a !== b);

let c = "10";
console.log(c == a); //true
console.log(c === a); //false
